"""Generate the shared fixtures of the Rust agent from the Python code.

The Python implementation is the oracle (agent-rs/PLAN.md section 9.2): every
fixture file is produced by calling the real graphyard functions on a fixed
corpus under the Django test settings, with clocks and the environment
injected. The Rust tests embed the files with ``include_str!``;
``tests/test_agent_rs_fixtures.py`` runs ``--check`` and fails when a
committed file differs from a fresh render.

Usage::

    uv run python agent-rs/fixtures/generate.py           # rewrite every file
    uv run python agent-rs/fixtures/generate.py --check   # exit 1 on drift
    uv run python agent-rs/fixtures/generate.py --list    # print the file names

Builders live in sibling modules ``gen_<topic>.py`` (one or more per slice),
each exporting ``GENERATORS: dict[str, Callable[[], object]]`` that maps a
fixture file name (relative to this directory) to a function returning its
content. They are discovered automatically, so slices add files without
editing this driver.

Rendering rules (Rust parses the files with ``serde_json``):

* ``json.dumps(content, indent=1, ensure_ascii=True, allow_nan=False)`` plus a
  final newline. Object key order is kept as the builder wrote it, because
  key order is part of the contract in places (configs, tags); builders that
  need a canonical order sort explicitly.
* Non-finite floats are not JSON: builders encode them explicitly (for
  example as ``repr`` text), ``allow_nan=False`` rejects them otherwise.
* Library-derived (P2) messages are stored as ``{"class": ..., "p2": true}``.

Determinism: the driver re-executes itself with ``PYTHONHASHSEED=0``, removes
every ``DJANGO_*``, ``GRAPHYARD_*`` and ``INFLUX_*`` variable from the
environment, stops django-environ from reading ``src/django/.env`` and sets
up Django with ``config.settings.test``. Builders set the variables they need
themselves.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import sys
from collections.abc import Callable, Mapping
from pathlib import Path
from types import ModuleType

FIXTURES_DIR = Path(__file__).resolve().parent
REPO_ROOT = FIXTURES_DIR.parent.parent
SETTINGS_MODULE = "config.settings.test"
SCRUBBED_ENV_PREFIXES = ("DJANGO_", "GRAPHYARD_", "INFLUX_")

Builder = Callable[[], object]


def bootstrap_django() -> None:
    """Set up Django with the test settings and a deterministic environment."""
    for key in list(os.environ):
        if key.startswith(SCRUBBED_ENV_PREFIXES):
            del os.environ[key]
    os.environ["DJANGO_SETTINGS_MODULE"] = SETTINGS_MODULE
    for path in (REPO_ROOT / "src", REPO_ROOT / "src" / "django"):
        if str(path) not in sys.path:
            sys.path.insert(0, str(path))

    import environ

    # base.py calls ``environ.Env.read_env(<src/django/.env>)``; a developer's
    # .env must not leak into the fixtures.
    environ.Env.read_env = classmethod(lambda cls, *args, **kwargs: None)  # type: ignore[method-assign,assignment]

    import django

    django.setup()


def _load_module(path: Path) -> ModuleType:
    spec = importlib.util.spec_from_file_location(f"agent_rs_{path.stem}", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def discover_generators(directory: Path = FIXTURES_DIR) -> dict[str, Builder]:
    """Collect ``GENERATORS`` of every ``gen_*.py`` module, sorted by file name."""
    generators: dict[str, Builder] = {}
    owners: dict[str, str] = {}
    for path in sorted(directory.glob("gen_*.py")):
        module_generators: Mapping[str, Builder] = _load_module(path).GENERATORS
        for name, builder in module_generators.items():
            if name in generators:
                raise SystemExit(
                    f"fixture {name} is generated by both {owners[name]} and {path.name}"
                )
            generators[name] = builder
            owners[name] = path.name
    return dict(sorted(generators.items()))


def render(content: object) -> str:
    """Render fixture content exactly as it is committed."""
    return json.dumps(content, indent=1, ensure_ascii=True, allow_nan=False) + "\n"


def check_fixtures(
    generators: Mapping[str, Builder], directory: Path = FIXTURES_DIR
) -> list[str]:
    """Return the problems of the fixture files in ``directory``.

    A generated file that is missing or differs from a fresh render is
    reported as ``stale: <name>``; a ``*.json`` file in the top level of
    ``directory`` that no builder generates as ``orphan: <name>`` (a removed
    builder must take its file with it). Subdirectories are checked only for
    the generated files they hold.
    """
    problems = []
    for name, builder in generators.items():
        path = directory / name
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != render(builder()):
            problems.append(f"stale: {name}")
    for path in sorted(directory.glob("*.json")):
        if path.name not in generators:
            problems.append(f"orphan: {path.name}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check", action="store_true", help="exit 1 when a committed file is stale"
    )
    mode.add_argument("--list", action="store_true", help="print the fixture names")
    parser.add_argument(
        "--dir",
        type=Path,
        default=FIXTURES_DIR,
        help="fixture directory to check or write (default: this directory)",
    )
    args = parser.parse_args(argv)
    if os.environ.get("PYTHONHASHSEED") != "0":
        # Set and dict-of-set reprs in Python messages depend on the hash
        # seed; a fixed seed keeps every render identical.
        os.execve(
            sys.executable,
            [sys.executable, *sys.argv],
            {**os.environ, "PYTHONHASHSEED": "0"},
        )
    # Builder modules may import graphyard at module level.
    bootstrap_django()
    generators = discover_generators()
    if args.list:
        for name in generators:
            print(name)
        return 0
    if args.check:
        problems = check_fixtures(generators, args.dir)
        for problem in problems:
            print(f"{problem} (run `just rs-fixtures`)", file=sys.stderr)
        return 1 if problems else 0
    for name, builder in generators.items():
        path = args.dir / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(builder()), encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
